'use strict';
const assert = require('node:assert/strict');
const {filter, paginate} = require('../web/library-core.js');
const fs = require('node:fs');
const skills = JSON.parse(fs.readFileSync('catalog/skills.json')).skills;
const sources = JSON.parse(fs.readFileSync('catalog/source-records.json'));
assert.equal(filter(skills, 'repair intake', {family: 'shop'})[0].id, 'np-shop-repair-intake');
assert.equal(filter(skills, 'repair intake', {family: 'bank'}).length, 0);
const nepal = filter(sources, '', {kind: 'nepal_institutional_reference'});
assert.equal(nepal.length, 117);
assert.equal(filter(sources, 'zzzzzzzzunlikely').length, 0);
const first = paginate(sources, 0), second = paginate(sources, 1);
assert.equal(first.records.length, 25);
assert.equal(new Set([...first.records, ...second.records].map(s => s.id)).size, 50);
assert.equal(paginate([], 99).page, 0);
assert.equal(paginate(sources, 999999).records.length, sources.length % 25);
assert.throws(() => paginate(sources, -1));
assert.throws(() => paginate(sources, 1, 1000));
console.log('Library filtering, collection separation and pagination passed');
